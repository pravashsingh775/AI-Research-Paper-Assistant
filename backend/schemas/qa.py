class QAEvidence(_QAModel):
    """
    Authoritative evidence/provenance object.

    IMPORTANT:

    This is NOT generated by the LLM.

    It represents trusted evidence originating from the RAG pipeline and
    therefore may contain document/chunk/page/provenance metadata.
    """

    evidence_id: str = Field(min_length=1)
    document_id: str = Field(min_length=1)
    paper_id: Optional[str] = None
    chunk_id: Optional[str] = None

    rank: Optional[int] = Field(default=None, gt=0)
    score: Optional[float] = None
    reranker_score: Optional[float] = None
    retrieval_score: Optional[float] = None

    section: str = Field(min_length=1)

    page: Optional[int] = Field(default=None, gt=0)
    page_end: Optional[int] = Field(default=None, gt=0)

    source_pages: tuple[int, ...] = ()

    title: Optional[str] = None
    text: str = Field(min_length=1)

    source_metadata: Mapping[str, Any] = Field(
        default_factory=dict
    )

    task_type: str = Field(
        default="qa",
        min_length=1,
    )

    section_priority: int = Field(ge=0)
    selection_order: int = Field(ge=0)

    @field_validator(
        "evidence_id",
        "document_id",
        "section",
        "task_type",
        mode="before",
    )
    @classmethod
    def nonempty_required_text(
        cls,
        value: Any,
        info,
    ) -> str:
        if not isinstance(value, str) or not value.strip():
            raise ValueError(
                f"{info.field_name} must be a non-empty string."
            )

        return value.strip()

    @field_validator(
        "paper_id",
        "chunk_id",
        "title",
        mode="before",
    )
    @classmethod
    def optional_text(
        cls,
        value: Any,
        info,
    ) -> Optional[str]:
        if value is None:
            return None

        if not isinstance(value, str) or not value.strip():
            raise ValueError(
                f"{info.field_name} must be non-empty when supplied."
            )

        return value.strip()

    @field_validator("text", mode="before")
    @classmethod
    def nonempty_evidence_text(cls, value: Any) -> str:
        if not isinstance(value, str) or not value.strip():
            raise ValueError("evidence text cannot be empty.")

        return value.strip()

    @field_validator(
        "score",
        "reranker_score",
        "retrieval_score",
    )
    @classmethod
    def finite_scores(
        cls,
        value: Optional[float],
        info,
    ) -> Optional[float]:
        if value is not None and not math.isfinite(value):
            raise ValueError(
                f"{info.field_name} must be finite."
            )

        return value

    @field_validator("source_pages")
    @classmethod
    def valid_source_pages(
        cls,
        value: tuple[int, ...],
    ) -> tuple[int, ...]:
        if any(page <= 0 for page in value):
            raise ValueError(
                "source_pages values must be >= 1."
            )

        if value != tuple(sorted(set(value))):
            raise ValueError(
                "source_pages must be sorted and unique."
            )

        return value

    @model_validator(mode="after")
    def validate_page_range(self) -> "QAEvidence":
        if (
            self.page is not None
            and self.page_end is not None
            and self.page > self.page_end
        ):
            raise ValueError(
                "page cannot exceed page_end."
            )

        if self.source_pages:
            if (
                self.page is not None
                and self.source_pages[0] != self.page
            ):
                raise ValueError(
                    "source_pages start does not match page."
                )

            if (
                self.page_end is not None
                and self.source_pages[-1] != self.page_end
            ):
                raise ValueError(
                    "source_pages end does not match page_end."
                )

        return self


