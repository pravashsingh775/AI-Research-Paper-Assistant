# ---------------------------------------------------------------------------
# Primitive LLM evidence reference
# ---------------------------------------------------------------------------


def _validate_evidence_reference(
    value: Any,
) -> int:
    """
    Validate one LLM evidence reference.

    Important:
        bool is rejected even though bool subclasses int in Python.

    Accepted:
        1
        6
        10

    Rejected:
        True
        False
        0
        -1
        1.5
        "6"
        None
    """

    if isinstance(value, bool):
        raise ValueError(
            "evidence references must be integers, not booleans."
        )

    if not isinstance(value, int):
        raise ValueError(
            "evidence references must be integers."
        )

    if value < 1:
        raise ValueError(
            "evidence references must be >= 1."
        )

    return value


