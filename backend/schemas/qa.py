class QAParsedOutput(_QAModel):
    """
    Exact structured QA generation payload.

    The LLM identifies evidence by numeric reference only.

    Example:

        {
            "question": "What ...?",
            "answer": "...",
            "grounded": true,
            "evidence": [6, 8, 10]
        }

    These numbers refer to evidence items supplied in the RAG context.

    They are NOT provenance objects and MUST NOT be interpreted as
    document/chunk/page metadata.

    Trusted provenance is resolved separately from the pipeline's evidence
    collection.
    """

    # Provider echo is optional at the parser boundary for backward
    # compatibility. The RAG pipeline always injects the trusted API question
    # before constructing the final QAResponse.
    question: Optional[str] = None

    answer: str
    grounded: bool

    # IMPORTANT:
    #
    # Do NOT change this back to:
    #
    #     tuple[QAEvidenceReference, ...]
    #
    # because the current LLM contract emits:
    #
    #     [6, 8, 10]
    #
    # not:
    #
    #     [{"evidence_number": 6}, ...]
    evidence: tuple[int, ...]

    @field_validator("question", mode="before")
    @classmethod
    def validate_question(cls, value: Any) -> Optional[str]:
        if value is None:
            return None

        if not isinstance(value, str):
            raise ValueError("question must be a string when supplied.")

        value = " ".join(value.split()).strip()

        if not value:
            raise ValueError("question cannot be empty when supplied.")

        return value

    @field_validator("answer", mode="before")
    @classmethod
    def validate_answer(cls, value: Any) -> str:
        if not isinstance(value, str):
            raise ValueError("answer must be a string.")

        value = value.strip()

        if not value:
            raise ValueError("answer cannot be empty.")

        return value

    @field_validator("evidence", mode="before")
    @classmethod
    def validate_evidence(
        cls,
        value: Any,
    ) -> Any:
        if value is None:
            raise ValueError(
                "evidence must be a list/tuple of integer references."
            )

        if isinstance(value, (str, bytes)):
            raise ValueError(
                "evidence must be a sequence of integer references."
            )

        try:
            values = list(value)
        except TypeError as exc:
            raise ValueError(
                "evidence must be a sequence of integer references."
            ) from exc

        return tuple(
            _validate_evidence_reference(item)
            for item in values
        )

    @model_validator(mode="after")
    def validate_evidence_numbers(self) -> "QAParsedOutput":
        numbers = self.evidence

        if len(numbers) != len(set(numbers)):
            raise ValueError(
                "evidence reference values must be unique."
            )

        if self.grounded and not numbers:
            raise ValueError(
                "grounded=True requires at least one evidence reference."
            )

        return self


