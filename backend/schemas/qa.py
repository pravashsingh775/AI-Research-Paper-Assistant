def run_self_test() -> None:
    """
    Deterministic schema-only acceptance tests.

    No model, network, FAISS, PDF, or external files are required.
    """

    # ------------------------------------------------------------------
    # 1. Valid request
    # ------------------------------------------------------------------

    request = QARequest(
        document_id="paper_A",
        question="What dataset did the authors use?",
        session_id="session_001",
    )

    assert request.document_id == "paper_A"
    assert request.question == (
        "What dataset did the authors use?"
    )

    # ------------------------------------------------------------------
    # 2-5. Invalid requests
    # ------------------------------------------------------------------

    invalid_requests = (
        {
            "document_id": "paper_A",
            "question": "",
        },
        {
            "document_id": "paper_A",
            "question": "   ",
        },
        {
            "document_id": "",
            "question": "What model was used?",
        },
        {
            "document_id": "   ",
            "question": "What model was used?",
        },
        {
            "question": "What model was used?",
        },
    )

    for payload in invalid_requests:
        try:
            QARequest(**payload)
        except Exception:
            pass
        else:
            raise AssertionError(
                f"Invalid QARequest accepted: {payload!r}"
            )

    # ------------------------------------------------------------------
    # 6. Valid authoritative evidence
    # ------------------------------------------------------------------

    evidence = QAEvidence(
        evidence_id="ev_1",
        document_id="paper_A",
        paper_id="paper_A",
        chunk_id="chunk_17",
        rank=1,
        score=0.91,
        reranker_score=0.88,
        retrieval_score=0.84,
        section="Dataset",
        page=5,
        page_end=5,
        source_pages=(5,),
        title="Example Paper",
        text="The experiments use the XYZ dataset.",
        task_type="qa",
        section_priority=10,
        selection_order=0,
    )

    # ------------------------------------------------------------------
    # 7. Valid citation
    # ------------------------------------------------------------------

    citation = QACitation(
        evidence_index=1,
        document_id="paper_A",
        paper_id="paper_A",
        chunk_id="chunk_17",
        section="Dataset",
        page=5,
        page_end=5,
        source_pages=(5,),
        rank=1,
        score=0.91,
        retrieval_score=0.84,
        reranker_score=0.88,
        label="Example Paper — Dataset, p. 5",
    )

    # ------------------------------------------------------------------
    # 8. CRITICAL:
    #    Current LLM format [6, 8, 10]
    # ------------------------------------------------------------------

    parsed = QAParsedOutput(
        question="What dataset did the authors use?",
        answer=(
            "The paper uses the XYZ dataset. "
            "[Evidence 6]"
        ),
        grounded=True,
        evidence=[6, 8, 10],
    )

    assert parsed.evidence == (6, 8, 10)

    # Parser boundary may accept a missing provider echo; the pipeline must
    # populate it before a final QAResponse is constructed.
    legacy_parsed = QAParsedOutput(
        answer="The paper uses the XYZ dataset.",
        grounded=True,
        evidence=[6],
    )
    assert legacy_parsed.question is None

    # ------------------------------------------------------------------
    # 9. Single integer evidence reference
    # ------------------------------------------------------------------

    single_reference = QAParsedOutput(
        question="What supports the answer?",
        answer="The answer is supported by the paper.",
        grounded=True,
        evidence=[6],
    )

    assert single_reference.evidence == (6,)

    # ------------------------------------------------------------------
    # 10. Duplicate references rejected
    # ------------------------------------------------------------------

    try:
        QAParsedOutput(
            question="Duplicate evidence?",
            answer="Duplicate evidence.",
            grounded=True,
            evidence=[6, 6],
        )
    except Exception:
        pass
    else:
        raise AssertionError(
            "Duplicate evidence references were accepted."
        )

    # ------------------------------------------------------------------
    # 11. Invalid reference values rejected
    # ------------------------------------------------------------------

    invalid_evidence_values = (
        [0],
        [-1],
        [True],
        [False],
        ["6"],
        [1.5],
    )

    for invalid_values in invalid_evidence_values:
        try:
            QAParsedOutput(
                question="Invalid evidence?",
                answer="Invalid evidence.",
                grounded=True,
                evidence=invalid_values,
            )
        except Exception:
            pass
        else:
            raise AssertionError(
                "Invalid evidence reference accepted: "
                f"{invalid_values!r}"
            )

    # ------------------------------------------------------------------
    # 12. Final QA response
    # ------------------------------------------------------------------

    response = QAResponse(
        document_id="paper_A",
        question=request.question,
        answer=parsed.answer,
        status=QAStatus.SUCCESS,
        success=True,
        grounded=True,
        evidence=(evidence,),
        citations=(citation,),
        structured_output=parsed,
    )

    assert response.document_id == "paper_A"
    assert response.question == request.question
    assert response.structured_output is not None
    assert response.structured_output.question == response.question
    assert response.structured_output.evidence == (
        6,
        8,
        10,
    )

    # ------------------------------------------------------------------
    # 13. Question echo is mandatory and preserved
    # ------------------------------------------------------------------

    assert parsed.question == "What dataset did the authors use?"

    try:
        QAParsedOutput(
            question="",
            answer="This must fail.",
            grounded=False,
            evidence=[],
        )
    except Exception:
        pass
    else:
        raise AssertionError(
            "Empty LLM question echo was accepted."
        )

    # ------------------------------------------------------------------
    # 14. Cross-document evidence rejected
    # ------------------------------------------------------------------

    wrong_evidence = evidence.model_copy(
        update={
            "document_id": "paper_B",
        }
    )

    try:
        QAResponse(
            document_id="paper_A",
            question="What dataset did the authors use?",
            answer="Wrong paper evidence.",
            status=QAStatus.SUCCESS,
            success=True,
            grounded=True,
            evidence=(wrong_evidence,),
        )
    except Exception:
        pass
    else:
        raise AssertionError(
            "Cross-document evidence was accepted."
        )

    # ------------------------------------------------------------------
    # 15. Insufficient evidence state
    # ------------------------------------------------------------------

    insufficient = QAResponse(
        document_id="paper_A",
        question=(
            "What was the exact electricity cost of training?"
        ),
        answer=None,
        status=QAStatus.INSUFFICIENT_EVIDENCE,
        success=False,
        grounded=False,
    )

    assert insufficient.is_insufficient_evidence
    assert insufficient.answer is None

    # ------------------------------------------------------------------
    # 16. Serialization
    # ------------------------------------------------------------------

    dumped = response.model_dump()

    assert isinstance(dumped, dict)
    assert dumped["structured_output"]["evidence"] == (
        6,
        8,
        10,
    )

    # Pydantic keeps tuple[int, ...] in Python-mode model_dump().
    # JSON serialization correctly converts the tuple to a JSON array.
    json_dumped = response.model_dump_json()
    assert isinstance(json_dumped, str)

    import json

    decoded = json.loads(json_dumped)

    assert decoded["structured_output"]["evidence"] == [
        6,
        8,
        10,
    ]

    assert decoded["structured_output"]["question"] == (
        "What dataset did the authors use?"
    )

    print("backend/schemas/qa.py self-test: PASSED")


