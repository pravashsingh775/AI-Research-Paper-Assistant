class QAResponse(_QAModel):
    """
    Frontend/API representation of one evidence-grounded paper-QA result.

    Important distinction:

        structured_output.evidence
            -> integer references selected by the LLM

        evidence
            -> authoritative rich QAEvidence objects from RAG pipeline

        citations
            -> authoritative citation objects from RAG pipeline
    """

    document_id: str = Field(min_length=1)
    question: str = Field(min_length=1)

    answer: Optional[str] = None

    status: QAStatus

    success: bool
    grounded: bool

    # Trusted rich context evidence.
    evidence: tuple[QAEvidence, ...] = ()

    # Trusted pipeline citations.
    citations: tuple[QACitation, ...] = ()

    # Parsed LLM structure.
    #
    # evidence here is intentionally tuple[int, ...].
    structured_output: Optional[QAParsedOutput] = None

    validation: Optional[ValidationMetadata] = None

    diagnostics: Optional[QADiagnostics] = None

    error: Optional[QAError] = None

    @field_validator("document_id", mode="before")
    @classmethod
    def validate_response_document_id(
        cls,
        value: Any,
    ) -> str:
        if not isinstance(value, str) or not value.strip():
            raise ValueError(
                "document_id must be a non-empty string."
            )

        return value.strip()

    @field_validator("question", mode="before")
    @classmethod
    def validate_response_question(
        cls,
        value: Any,
    ) -> str:
        if not isinstance(value, str) or not value.strip():
            raise ValueError(
                "question must be a non-empty string."
            )

        return value.strip()

    @field_validator("answer", mode="before")
    @classmethod
    def validate_optional_answer(
        cls,
        value: Any,
    ) -> Optional[str]:
        if value is None:
            return None

        if not isinstance(value, str):
            raise ValueError(
                "answer must be a string or null."
            )

        value = value.strip()

        return value or None

    @model_validator(mode="after")
    def enforce_response_integrity(self) -> "QAResponse":
        """
        Enforce final document isolation and status invariants.

        Integer structured evidence references are deliberately NOT checked
        for document IDs here because they contain no provenance.

        Provenance checks happen against trusted QAEvidence/QACitation objects.
        """

        evidence_document_ids = {
            item.document_id
            for item in self.evidence
            if item.document_id
        }

        citation_document_ids = {
            item.document_id
            for item in self.citations
            if item.document_id
        }

        validation_document_ids = set()

        if self.validation is not None:
            for decision in self.validation.claim_decisions:
                if decision.document_id:
                    validation_document_ids.add(
                        decision.document_id
                    )

        for source_name, ids in (
            ("evidence", evidence_document_ids),
            ("citations", citation_document_ids),
            ("validation.claim_decisions", validation_document_ids),
        ):
            mismatched = ids - {self.document_id}

            if mismatched:
                raise ValueError(
                    f"{source_name} contains document IDs inconsistent "
                    f"with response.document_id="
                    f"{self.document_id!r}: "
                    f"{sorted(mismatched)!r}."
                )

        # ---------------------------------------------------------------
        # Structured-output question identity
        # ---------------------------------------------------------------

        if self.structured_output is not None:
            if self.structured_output.question is None:
                raise ValueError(
                    "structured_output.question must be populated by the "
                    "RAG pipeline before constructing QAResponse."
                )

            expected_question = " ".join(self.question.split()).casefold()
            returned_question = " ".join(
                self.structured_output.question.split()
            ).casefold()

            if returned_question != expected_question:
                raise ValueError(
                    "structured_output.question does not match "
                    "response.question."
                )

        # ---------------------------------------------------------------
        # Insufficient evidence state
        # ---------------------------------------------------------------

        if self.status is QAStatus.INSUFFICIENT_EVIDENCE:
            if self.success:
                raise ValueError(
                    "insufficient_evidence cannot have success=True."
                )

            if self.answer is not None:
                raise ValueError(
                    "insufficient_evidence must have answer=null."
                )

            if self.grounded:
                raise ValueError(
                    "insufficient_evidence cannot be grounded=True."
                )

            if self.evidence or self.citations:
                raise ValueError(
                    "insufficient_evidence must not contain "
                    "fabricated evidence/citations."
                )

        # ---------------------------------------------------------------
        # Success state
        # ---------------------------------------------------------------

        if self.status is QAStatus.SUCCESS:
            if not self.success:
                raise ValueError(
                    "success status requires success=True."
                )

            if self.answer is None:
                raise ValueError(
                    "success status requires a non-null answer."
                )

        return self

    @property
    def is_insufficient_evidence(self) -> bool:
        return self.status is QAStatus.INSUFFICIENT_EVIDENCE


