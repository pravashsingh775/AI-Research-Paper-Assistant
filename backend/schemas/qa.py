"""
Pydantic v2 contracts for uploaded-paper question answering.

This module defines DATA CONTRACTS only.

Important architecture:

    LLM structured output
        question = optional provider echo
        evidence = [6, 8, 10]
                    │
                    ▼
        canonical backend question + integer evidence references
                    │
                    ▼
    trusted RAG pipeline evidence
                    │
                    ▼
        QAEvidence objects
                    │
                    ▼
              QAResponse

The LLM is allowed to identify evidence only by numeric reference.
It must NOT manufacture document/chunk/page provenance.

The authoritative provenance objects are produced by the RAG pipeline.
The API layer is responsible for resolving the LLM evidence numbers against
that trusted evidence collection before constructing QAResponse.

This module contains DATA CONTRACTS only. It intentionally contains no RAG,
retrieval, embedding, FAISS, prompt, LLM, PDF, or validation algorithms.
"""

