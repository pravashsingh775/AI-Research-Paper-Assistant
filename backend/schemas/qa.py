class _QAModel(BaseModel):
    """
    Shared configuration for API/domain QA models.

    extra='ignore' is intentionally retained for response compatibility.
    Request models use _StrictRequest instead.
    """

    model_config = ConfigDict(
        from_attributes=True,
        populate_by_name=True,
        extra="ignore",
        validate_assignment=True,
    )


class _StrictRequest(_QAModel):
    """Strict configuration for user-controlled request payloads."""

    model_config = ConfigDict(
        from_attributes=True,
        populate_by_name=True,
        extra="forbid",
        validate_assignment=True,
    )


# ---------------------------------------------------------------------------
# Pipeline status
# ---------------------------------------------------------------------------


class QAStatus(str, Enum):
    """Terminal QA states exposed by RAGPipeline."""

    SUCCESS = "success"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"


# ---------------------------------------------------------------------------
# Request
# ---------------------------------------------------------------------------


class QARequest(_StrictRequest):
    """
    One question explicitly scoped to one uploaded research paper.
    """

    document_id: str = Field(min_length=1)
    question: str = Field(min_length=1)
    session_id: Optional[str] = Field(default=None, min_length=1)

    @field_validator("document_id", mode="before")
    @classmethod
    def validate_document_id(cls, value: Any) -> str:
        if not isinstance(value, str):
            raise ValueError("document_id must be a string.")

        value = value.strip()

        if not value:
            raise ValueError(
                "document_id cannot be empty or whitespace."
            )

        return value

    @field_validator("question", mode="before")
    @classmethod
    def validate_question(cls, value: Any) -> str:
        if not isinstance(value, str):
            raise ValueError("question must be a string.")

        value = value.strip()

        if not value:
            raise ValueError(
                "question cannot be empty or whitespace."
            )

        # Preserve scientific terminology and user wording.
        return value

    @field_validator("session_id", mode="before")
    @classmethod
    def validate_session_id(
        cls,
        value: Any,
    ) -> Optional[str]:
        if value is None:
            return None

        if not isinstance(value, str):
            raise ValueError(
                "session_id must be a string when supplied."
            )

        value = value.strip()

        if not value:
            raise ValueError(
                "session_id cannot be empty or whitespace."
            )

        return value


