"""
High-level paper-analysis orchestration for the AI Research Paper Assistant.

Responsibilities
----------------
This module receives the already-selected papers from research/search.py and
coordinates the seven analysis modules:

    summary
    model
    dataset
    methodology
    findings
    strengths
    weaknesses

It deliberately does NOT:
- retrieve papers
- call FAISS/SPECTER2
- rerank or sort papers
- load the corpus
- load PDFs
- perform OCR/chunking
- implement RAG/Q&A
- instantiate a direct LLM client
- duplicate analysis logic from backend/analysis/

The injected analysis modules own extraction/generation logic.

The service is designed to be resilient at the paper level: one malformed or
failed paper produces an explicit failed/partial result rather than silently
destroying the other analyses.
"""

from __future__ import annotations

import logging
import math
import time
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Callable, Mapping, Optional, Protocol, Sequence

logger = logging.getLogger(__name__)

UNAVAILABLE_TEXT = "Not available in the provided content."
UNDETERMINABLE_TEXT = (
    "Cannot be reliably determined from the available content."
)
DEFAULT_ANALYSIS_MODE = "abstract"


# ============================================================================
# Exceptions
# ============================================================================


class PaperAnalysisError(RuntimeError):
    """Base exception for high-level paper-analysis failures."""


class InvalidPaperError(PaperAnalysisError, ValueError):
    """Raised when an input paper violates the analyzer contract."""


class AnalysisValidationError(PaperAnalysisError, ValueError):
    """Raised when an analysis module returns malformed output."""


class EvidenceValidationError(PaperAnalysisError, ValueError):
    """Raised when an evidence-bearing result violates evidence rules."""


# ============================================================================
# Status / evidence models
# ============================================================================


class AnalysisStatus(str, Enum):
    """Per-paper analysis status."""

    SUCCESS = "success"
    PARTIAL = "partial"
    FAILED = "failed"


class Confidence(str, Enum):
    """
    Qualitative extraction confidence.

    This is extraction certainty, NOT scientific truth and NOT a calibrated
    probability.
    """

    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


@dataclass(frozen=True)
class Evidence:
    """Source-grounding information attached to an analytical claim."""

    text: str
    source: str = "provided_content"
    confidence: Confidence = Confidence.MEDIUM

    def __post_init__(self) -> None:
        if not isinstance(self.text, str) or not self.text.strip():
            raise EvidenceValidationError(
                "Evidence text must be a non-empty string."
            )

        if not isinstance(self.source, str) or not self.source.strip():
            raise EvidenceValidationError(
                "Evidence source must be a non-empty string."
            )

        if not isinstance(self.confidence, Confidence):
            raise EvidenceValidationError(
                "Evidence confidence must be a Confidence enum value."
            )


@dataclass(frozen=True)
class AnalysisField:
    """
    Generic structured analysis field.

    value can be a string, list, mapping, scalar, or None depending on the
    injected analysis module's schema. evidence is optional because some
    existing modules may not expose evidence yet; the orchestrator never
    fabricates it.
    """

    value: Any
    evidence: tuple[Evidence, ...] = ()
    confidence: Optional[Confidence] = None

    def __post_init__(self) -> None:
        if self.confidence is not None and not isinstance(
            self.confidence, Confidence
        ):
            raise AnalysisValidationError(
                "AnalysisField.confidence must be a Confidence enum."
            )

        for item in self.evidence:
            if not isinstance(item, Evidence):
                raise AnalysisValidationError(
                    "AnalysisField.evidence contains an invalid item."
                )


@dataclass(frozen=True)
class PaperAnalysis:
    """
    Structured analysis for one selected research paper.

    Metadata is preserved from search.py and is never regenerated by this
    service.
    """

    document_id: str
    rank: int
    title: str

    summary: Any
    model: Any
    dataset: Any
    methodology: Any
    findings: Any
    strengths: Any
    weaknesses: Any

    status: AnalysisStatus = AnalysisStatus.SUCCESS
    error_message: Optional[str] = None

    authors: Any = None
    published_date: Any = None
    category: Any = None
    retrieval_score: Any = None
    reranker_score: Any = None
    final_score: Any = None

    evidence: tuple[Evidence, ...] = ()
    component_status: Mapping[str, str] = field(default_factory=dict)
    analysis_mode: str = DEFAULT_ANALYSIS_MODE
    latency_seconds: Optional[float] = None

    def __post_init__(self) -> None:
        if not self.document_id.strip():
            raise InvalidPaperError(
                "PaperAnalysis.document_id cannot be empty."
            )

        if self.rank <= 0:
            raise InvalidPaperError(
                "PaperAnalysis.rank must be positive."
            )

        if not self.title.strip():
            raise InvalidPaperError(
                "PaperAnalysis.title cannot be empty."
            )

        if self.status == AnalysisStatus.SUCCESS and self.error_message:
            raise AnalysisValidationError(
                "Successful PaperAnalysis cannot contain error_message."
            )

        if self.status != AnalysisStatus.SUCCESS and not self.error_message:
            raise AnalysisValidationError(
                "Partial/failed PaperAnalysis requires error_message."
            )


@dataclass(frozen=True)
class ResearchAnalysisResponse:
    """Structured response containing paper analyses in original rank order."""

    query: str
    analyzed_count: int
    papers: list[PaperAnalysis]
    requested_count: int = 0
    failed_count: int = 0
    partial_count: int = 0
    total_latency_seconds: Optional[float] = None

    def __post_init__(self) -> None:
        if self.analyzed_count != len(self.papers):
            raise AnalysisValidationError(
                "analyzed_count does not match papers length."
            )

        if self.failed_count < 0 or self.partial_count < 0:
            raise AnalysisValidationError(
                "Failure counters cannot be negative."
            )


